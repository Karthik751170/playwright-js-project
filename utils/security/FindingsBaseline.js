/**
 * FindingsBaseline.js
 * Persists findings between runs and diffs against the previous run.
 *
 * Without this, the suite is an audit rather than a regression gate: a control
 * that silently degrades from PASS to WARN is invisible unless somebody reads
 * the HTML. The baseline turns "what is the state" into "what changed".
 *
 * The baseline is a committed artifact -- review changes to it in PRs the same
 * way you would review a snapshot test update.
 */

const fs = require('fs');
const path = require('path');

const DEFAULT_PATH = path.join(process.cwd(), 'config', 'security-baseline.json');
/** Ranked worst-first so we can tell degradation from improvement. */
const RANK = { FAIL: 4, WARN: 3, INCONCLUSIVE: 2, SUPPRESSED: 1, PASS: 0 };

class FindingsBaseline {
  constructor(baselinePath = process.env.SECURITY_BASELINE_PATH || DEFAULT_PATH) {
    this.baselinePath = baselinePath;
    this.previous = this.load();
  }

  load() {
    try {
      if (fs.existsSync(this.baselinePath)) {
        const parsed = JSON.parse(fs.readFileSync(this.baselinePath, 'utf-8'));
        return parsed.findings || {};
      }
    } catch (e) {
      console.warn(`[Baseline] Could not read ${this.baselinePath}: ${e.message}`);
    }
    return null; // null = no baseline yet, distinct from an empty baseline
  }

  /** Stable identity for a finding across runs. */
  static keyFor(record) {
    return `${record.code}::${record.name}`;
  }

  /**
   * @returns {{ isFirstRun: boolean, regressions: object[], improvements: object[],
   *             added: object[], removed: object[], unchanged: number }}
   */
  diff(records) {
    const current = {};
    for (const r of records) {
      current[FindingsBaseline.keyFor(r)] = { status: r.status, severity: r.severity, actual: r.actual };
    }

    if (this.previous === null) {
      return { isFirstRun: true, regressions: [], improvements: [], added: [], removed: [], unchanged: 0, current };
    }

    const regressions = [];
    const improvements = [];
    const added = [];
    let unchanged = 0;

    for (const [key, now] of Object.entries(current)) {
      const before = this.previous[key];
      if (!before) {
        added.push({ key, status: now.status, actual: now.actual });
        continue;
      }
      const delta = (RANK[now.status] ?? 0) - (RANK[before.status] ?? 0);
      if (delta > 0) regressions.push({ key, from: before.status, to: now.status, actual: now.actual });
      else if (delta < 0) improvements.push({ key, from: before.status, to: now.status });
      else unchanged++;
    }

    const removed = Object.keys(this.previous)
      .filter((k) => !(k in current))
      .map((key) => ({ key, was: this.previous[key].status }));

    return { isFirstRun: false, regressions, improvements, added, removed, unchanged, current };
  }

  /** Writes the current run as the new baseline. */
  save(records, meta = {}) {
    const findings = {};
    for (const r of records) {
      findings[FindingsBaseline.keyFor(r)] = { status: r.status, severity: r.severity, actual: r.actual };
    }
    const payload = {
      generatedAt: new Date().toISOString(),
      note: 'Auto-generated by scripts/fullSecuritySuite.js. Review changes to this file in PRs: a PASS -> WARN/FAIL transition here is a security regression.',
      ...meta,
      findings,
    };
    fs.mkdirSync(path.dirname(this.baselinePath), { recursive: true });
    fs.writeFileSync(this.baselinePath, `${JSON.stringify(payload, null, 2)}\n`, 'utf-8');
    return this.baselinePath;
  }

  /** Human-readable diff for the console and the CI job summary. */
  static formatDiff(d) {
    if (d.isFirstRun) {
      return '  No previous baseline: this run establishes it. Commit config/security-baseline.json to enable regression detection.';
    }
    const lines = [];
    if (d.regressions.length > 0) {
      lines.push(`  REGRESSIONS (${d.regressions.length}) — a control got worse since the baseline:`);
      d.regressions.forEach((r) => lines.push(`    • ${r.key}: ${r.from} -> ${r.to}\n      ${r.actual}`));
    }
    if (d.added.length > 0) {
      lines.push(`  NEW controls (${d.added.length}):`);
      d.added.forEach((a) => lines.push(`    • ${a.key} [${a.status}]`));
    }
    if (d.removed.length > 0) {
      lines.push(`  REMOVED controls (${d.removed.length}) — verify this was intentional:`);
      d.removed.forEach((r) => lines.push(`    • ${r.key} (was ${r.was})`));
    }
    if (d.improvements.length > 0) {
      lines.push(`  Improvements (${d.improvements.length}):`);
      d.improvements.forEach((i) => lines.push(`    • ${i.key}: ${i.from} -> ${i.to}`));
    }
    if (lines.length === 0) lines.push(`  No change from baseline (${d.unchanged} controls identical).`);
    return lines.join('\n');
  }
}

module.exports = FindingsBaseline;
